    /// <summary>
    /// Local cosmetic facial controller for both the current CC5/Headshot face
    /// and the previous Blender face. It resolves every matching blendshape
    /// under the component, so head, teeth, tongue, tearline, eye-occlusion,
    /// and eyelash follower meshes stay synchronized after the head graft.
    /// </summary>
    public class BundyLipsync : MonoBehaviour
    {
        [Header("Audio")]
        public AudioSource voiceSource;
        [Tooltip("Linear gain applied to the RMS level before mapping to facial motion.")]
        public float gain = 9f;
        [Tooltip("Jaw-open speed per second while the audio envelope is rising.")]
        public float attackSpeed = 22f;
        [Tooltip("Jaw-close speed per second while the audio envelope is falling.")]
        public float releaseSpeed = 9f;
        [Range(0f, 1f)]
        [Tooltip("Maximum normalized Jaw_Open weight generated by speech.")]
        public float maxJaw = 0.65f;
        [Range(0.2f, 1f)]
        [Tooltip("Response curve applied to the per-clip-normalized envelope; below 1 lifts quiet syllables so the mouth visibly articulates.")]
        public float envelopeExponent = 0.65f;
        [Range(0f, 1f)]
        [Tooltip("Minimum jaw opening (as a fraction of maxJaw) held on any audible syllable, so the mouth stays clearly parted while he talks instead of fluttering shut between words.")]
        public float speechFloor = 0.35f;
        [Tooltip("Add low-cost CC5 viseme variation on top of the amplitude envelope.")]
        public bool animateVisemes = true;

        [Header("Jaw bone")]
        [Tooltip("Rotate the CC5 jaw bone with the speech envelope. The 2026-07-22 editor proof showed Jaw_Open at 100 is visually a no-op (lips-only corrective morph) while the real mouth opening is CC_Base_JawRoot rotation.")]
        public bool driveJawBone = true;
        [Tooltip("Jaw bone local-Z rotation in degrees at full envelope. The grafted face rig's jaw pivot sits ~4.8m from the mouth (scaled CC skeleton), so ~0.5deg is a natural talking mouth and ~1deg reads as shouting. Negative flips direction if an export changes the axis.")]
        public float maxJawBoneDegrees = 0.8f;

        private const string JawBoneName = "CC_Base_JawRoot";
        private Transform _jawBone;
        private Quaternion _jawBoneBaseLocalRotation = Quaternion.identity;
        private bool _jawBoneResolveLogged;

        [Header("Auto blink")]
        public bool autoBlink = true;
        public float blinkIntervalMin = 2.5f;
        public float blinkIntervalMax = 6f;
        public float blinkCloseSeconds = 0.09f;
        public float blinkOpenSeconds = 0.14f;
        [Min(0.1f)]
        [Tooltip("Delay before the first deterministic blink after this instance awakens.")]
        public float firstBlinkDelaySeconds = 1.25f;
        [Tooltip("Write a one-shot runtime proof when the first blink reaches its applied peak weights.")]
        public bool logFirstBlinkDiagnostics = true;
        [Tooltip("Write a one-shot runtime proof of the speech envelope (peak RMS/jaw) after the first vocal finishes on the voice source.")]
        public bool logFirstSpeechDiagnostics = true;

        private const int SampleCount = 256;
        private const float RebindIntervalSeconds = 1f;

        // Keep these names exact and centralized. FindBlendShape also accepts
        // exporter-prefixed names through an ordinal suffix match.
        private static readonly string[] DrivenChannels =
        {
            "Jaw_Open",
            "Jaw_Follow",
            "V_Open",
            "V_Wide",
            "V_Tight_O",
            "V_Dental_Lip",
            "V_Lip_Open",
            "Eye_Blink_L",
            "Eye_Blink_R",
            "Lid_Close",
            "Mouth_Corner_Pull_L",
            "Mouth_Corner_Pull_R",
            "Mouth_Smile_L",
