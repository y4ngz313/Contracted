        private sealed class ShapeTarget
        {
            internal readonly SkinnedMeshRenderer Renderer;
            internal readonly int Index;

            internal ShapeTarget(SkinnedMeshRenderer renderer, int index)
            {
                Renderer = renderer;
                Index = index;
            }
        }

        private readonly Dictionary<string, List<ShapeTarget>> _targets =
            new Dictionary<string, List<ShapeTarget>>(StringComparer.Ordinal);
        private readonly float[] _samples = new float[SampleCount];

        private float _jaw;
        private float _blink;
        private float _nextBlinkAt;
        private float _blinkPhaseEnd;
        private float _nextResolveAt;
        private bool _blinkClosing;
        private bool _blinkActive;
        private bool _resolved;
        private bool _missingBindingWarningLogged;
        private bool _firstBlinkStartedLogged;
        private bool _firstBlinkPeakLogged;
        private bool _speechProbeActive;
        private bool _speechProbeLogged;
        private bool _speechProbeClipDriven;
        private float _speechProbeStartedAt;
        private float _speechProbePeakRms;
        private float _speechProbePeakJaw;

        private const float EnvelopeBinSeconds = 0.05f;
        // Normalized-envelope level below which a bin counts as a between-words pause.
        private const float SpeechSilenceGate = 0.06f;
        // Per-clip normalized RMS envelopes (peak = 1). Keyed by clip name; loose-loaded
        // clips are created via AudioClip.Create so GetData is always available for them.
        private static readonly Dictionary<string, float[]> s_envelopeCache =
            new Dictionary<string, float[]>(StringComparer.Ordinal);
        private AudioClip _activeVoiceClip;
        private float[] _activeEnvelope;
        private float _activeVoiceClipStartedAt;

        public bool IsResolved => _resolved;
        public int BoundRendererCount { get; private set; }
        public int BoundChannelCount { get; private set; }

        private void Awake()
        {
            RebuildBindings();
            ScheduleNextBlink(Time.time, true);
        }

        private void OnTransformChildrenChanged()
        {
            // The production head is grafted beneath the existing chainsaw
            // prefab. Re-resolve after hierarchy changes instead of relying on
            // whatever happened to exist during Awake.
            _resolved = false;
            _nextResolveAt = Time.time;
        }

        private void OnDisable()
        {
            ResetDrivenWeights();
        }

        /// <summary>
        /// Rebuild all renderer/channel bindings. This is safe to call after a
        /// runtime or editor-time head graft.
        /// </summary>
        public void RebuildBindings()
        {
            _targets.Clear();
            BoundRendererCount = 0;
            BoundChannelCount = 0;

            var boundRenderers = new HashSet<SkinnedMeshRenderer>();
            SkinnedMeshRenderer[] renderers = GetComponentsInChildren<SkinnedMeshRenderer>(true);
            for (int rendererIndex = 0; rendererIndex < renderers.Length; rendererIndex++)
            {
                SkinnedMeshRenderer renderer = renderers[rendererIndex];
                if (renderer == null || renderer.sharedMesh == null)
                    continue;

                for (int channelIndex = 0; channelIndex < DrivenChannels.Length; channelIndex++)
                {
                    string channel = DrivenChannels[channelIndex];
                    int blendShapeIndex = FindBlendShape(renderer, channel);
                    if (blendShapeIndex < 0)
                        continue;

                    if (!_targets.TryGetValue(channel, out List<ShapeTarget> channelTargets))
                    {
                        channelTargets = new List<ShapeTarget>();
                        _targets.Add(channel, channelTargets);
                    }

                    channelTargets.Add(new ShapeTarget(renderer, blendShapeIndex));
                    boundRenderers.Add(renderer);
                }
            }

            BoundRendererCount = boundRenderers.Count;
            BoundChannelCount = _targets.Count;
            _resolved = HasTargets("Jaw_Open") || HasTargets("Jaw_Follow");
            _nextResolveAt = Time.time + RebindIntervalSeconds;

            ResolveJawBone();

            if (voiceSource == null)
                voiceSource = FindVoiceSource();

            if (_resolved)
            {
                _missingBindingWarningLogged = false;
            }
            else if (!_missingBindingWarningLogged)
            {
                _missingBindingWarningLogged = true;
                LogFaceWarning("[BundyLipsync] No Jaw_Open or Jaw_Follow blendshape was found under " + name);
            }
        }

        public int GetBoundTargetCount(string channel)
        {
            return !string.IsNullOrEmpty(channel) && _targets.TryGetValue(channel, out List<ShapeTarget> values)
                ? values.Count
                : 0;
        }

        public void TriggerBlink()
        {
            _blinkActive = true;
            _blinkClosing = true;
            _blinkPhaseEnd = Time.time + Mathf.Max(0.01f, blinkCloseSeconds);
            if (logFirstBlinkDiagnostics && !_firstBlinkStartedLogged)
            {
                _firstBlinkStartedLogged = true;
                LogFaceWarning(
                    "[BundyFace] First blink started on '" + name + "': resolved=" + _resolved +
                    ", targets=(L:" + GetBoundTargetCount("Eye_Blink_L") +
                    ",R:" + GetBoundTargetCount("Eye_Blink_R") +
                    ",Lid:" + GetBoundTargetCount("Lid_Close") + ").");
            }
        }

        private void ResolveJawBone()
        {
            Transform found = null;
            Transform[] children = GetComponentsInChildren<Transform>(true);
            for (int i = 0; i < children.Length; i++)
            {
                if (children[i] != null && string.Equals(children[i].name, JawBoneName, StringComparison.Ordinal))
                {
                    found = children[i];
                    break;
                }
            }

            if (found == null)
            {
                _jawBone = null;
                return;
            }

            if (!ReferenceEquals(found, _jawBone))
            {
                _jawBone = found;
                _jawBoneBaseLocalRotation = found.localRotation;
                if (!_jawBoneResolveLogged)
                {
                    _jawBoneResolveLogged = true;
                    LogFaceWarning(
                        "[BundyFace] Jaw bone resolved on '" + name + "': '" + JawBoneName +
                        "', baseLocalEuler=" + found.localEulerAngles.ToString("F2") +
                        ", driveJawBone=" + driveJawBone +
                        ", maxJawBoneDegrees=" + maxJawBoneDegrees.ToString("F2") + ".");
                }
            }
        }

        // The morph channels stay driven for lip shaping, but the visible mouth
        // opening comes from this bone. Rotation is applied about the bone's
        // local Z axis relative to its authored rest rotation; because nothing
        // else animates the CC face skeleton there is no write conflict.
        private void ApplyJawBone(float normalizedJaw)
        {
            if (!driveJawBone || _jawBone == null)
                return;
            _jawBone.localRotation = _jawBoneBaseLocalRotation *
                Quaternion.AngleAxis(Mathf.Clamp01(normalizedJaw) * maxJawBoneDegrees, Vector3.forward);
        }

        private static int FindBlendShape(SkinnedMeshRenderer renderer, string shapeName)
        {
            Mesh mesh = renderer.sharedMesh;
            int direct = mesh.GetBlendShapeIndex(shapeName);
            if (direct >= 0)
                return direct;

            for (int i = 0; i < mesh.blendShapeCount; i++)
            {
                string candidate = mesh.GetBlendShapeName(i);
                if (candidate.EndsWith(shapeName, StringComparison.Ordinal))
                    return i;
            }

            return -1;
        }

        private AudioSource FindVoiceSource()
        {
            AudioSource fallback = null;
            AudioSource[] parentSources = GetComponentsInParent<AudioSource>(true);
            for (int i = 0; i < parentSources.Length; i++)
            {
                AudioSource source = parentSources[i];
                if (source == null)
                    continue;
                if (fallback == null)
                    fallback = source;
                if (source.name.IndexOf("voice", StringComparison.OrdinalIgnoreCase) >= 0)
                    return source;
            }

            AudioSource[] childSources = GetComponentsInChildren<AudioSource>(true);
            for (int i = 0; i < childSources.Length; i++)
            {
                AudioSource source = childSources[i];
                if (source == null)
                    continue;
                if (fallback == null)
                    fallback = source;
                if (source.name.IndexOf("voice", StringComparison.OrdinalIgnoreCase) >= 0)
                    return source;
            }

            return fallback;
        }

        private void LateUpdate()
        {
            if (!_resolved)
            {
                if (Time.time >= _nextResolveAt)
                    RebuildBindings();
                if (!_resolved)
                    return;
            }

            UpdateJaw();
            UpdateBlink();
            ApplyFace();
        }

        /// <summary>
        /// Tell the lipsync a vocal clip just started on the voice source. The jaw is then
        /// driven from the clip's own sample data. This is the production path: the in-game
        /// 2026-07-22 probe proved GetOutputData on the spatialized CreatureVoice reads ~0
        /// (peakRms=0.0000 over a 2.26s vocal), so output capture cannot drive the jaw.
        /// </summary>
        public void NotifyVocal(AudioClip clip)
        {
            if (clip == null)
                return;

            float[] envelope = GetOrBuildEnvelope(clip);
            if (envelope == null)
                return;

            _activeVoiceClip = clip;
            _activeEnvelope = envelope;
            _activeVoiceClipStartedAt = Time.time;
        }

        private static float[] GetOrBuildEnvelope(AudioClip clip)
        {
            if (s_envelopeCache.TryGetValue(clip.name, out float[] cached))
                return cached;

            float[] envelope = null;
            try
            {
                int channels = Mathf.Max(1, clip.channels);
                int frames = clip.samples;
                if (frames > 0)
                {
                    var data = new float[frames * channels];
                    if (clip.GetData(data, 0))
                    {
                        int framesPerBin = Mathf.Max(1, Mathf.RoundToInt(clip.frequency * EnvelopeBinSeconds));
                        int binCount = (frames + framesPerBin - 1) / framesPerBin;
                        envelope = new float[binCount];
                        float peak = 0f;
                        for (int bin = 0; bin < binCount; bin++)
                        {
                            int start = bin * framesPerBin * channels;
                            int end = Mathf.Min(data.Length, start + framesPerBin * channels);
                            float sum = 0f;
                            for (int i = start; i < end; i++)
                                sum += data[i] * data[i];
                            int count = Mathf.Max(1, end - start);
                            envelope[bin] = Mathf.Sqrt(sum / count);
                            if (envelope[bin] > peak)
                                peak = envelope[bin];
                        }

                        // Normalize per clip so every voiceline peaks at maxJaw regardless of
                        // how hot it was mastered. A near-silent clip stays unnormalized.
                        if (peak > 0.005f)
                        {
                            for (int i = 0; i < binCount; i++)
                                envelope[i] /= peak;
                        }
                    }
                }
            }
            catch (Exception e)
            {
                LogFaceWarning("[BundyFace] Envelope build failed for '" + clip.name + "': " + e.GetType().Name + ": " + e.Message);
                envelope = null;
            }

            s_envelopeCache[clip.name] = envelope;
            return envelope;
        }

        private void UpdateJaw()
        {
            float target = 0f;
            float rms = 0f;
            bool clipDriven = false;

            if (_activeEnvelope != null && _activeVoiceClip != null)
            {
                float elapsed = Time.time - _activeVoiceClipStartedAt;
                if (elapsed >= 0f && elapsed < _activeVoiceClip.length)
                {
                    int bin = Mathf.Clamp((int)(elapsed / EnvelopeBinSeconds), 0, _activeEnvelope.Length - 1);
                    rms = _activeEnvelope[bin];
                    if (rms > SpeechSilenceGate)
                    {
                        float shaped = Mathf.Pow(Mathf.Clamp01(rms), Mathf.Max(0.2f, envelopeExponent));
                        target = maxJaw * Mathf.Max(Mathf.Clamp01(speechFloor), shaped);
                    }
                    clipDriven = true;
                }
                else
                {
                    _activeVoiceClip = null;
                    _activeEnvelope = null;
                }
            }

            bool playing = voiceSource != null && voiceSource.isPlaying;
            if (!clipDriven && playing)
            {
                // Legacy fallback for vocals nobody notified us about. Known to read ~0 for
                // spatialized sources; kept because it costs little and can only help.
                voiceSource.GetOutputData(_samples, 0);
                float sum = 0f;
                for (int i = 0; i < SampleCount; i++)
                    sum += _samples[i] * _samples[i];
                rms = Mathf.Sqrt(sum / SampleCount);
                target = Mathf.Clamp(rms * gain, 0f, maxJaw);
            }

            float speed = target > _jaw ? attackSpeed : releaseSpeed;
            _jaw = Mathf.MoveTowards(_jaw, target, speed * Time.deltaTime);

            UpdateSpeechProbe(clipDriven || playing, rms, clipDriven);
        }

        // Blink has a full in-game proof chain; speech has none. This one-shot
        // probe captures the first vocal played through the resolved voice
        // source and reports the peak audio envelope vs the peak jaw weight it
        // produced. peakRms≈0 while a vocal audibly played indicts the
        // GetOutputData/one-shot path; healthy rms with peakJaw≈0 indicts the
        // gain/mapping; healthy both means jaw sync works and any remaining
        // complaint is visual (amplitude/timing tuning).
        private void UpdateSpeechProbe(bool playing, float rms, bool clipDriven)
        {
            if (!logFirstSpeechDiagnostics || _speechProbeLogged)
                return;

            if (playing)
            {
                if (!_speechProbeActive)
                {
                    _speechProbeActive = true;
                    _speechProbeStartedAt = Time.time;
                    _speechProbePeakRms = 0f;
                    _speechProbePeakJaw = 0f;
                    _speechProbeClipDriven = false;
                }
                if (clipDriven)
                    _speechProbeClipDriven = true;
                if (rms > _speechProbePeakRms)
                    _speechProbePeakRms = rms;
                if (_jaw > _speechProbePeakJaw)
                    _speechProbePeakJaw = _jaw;
                return;
            }

            if (!_speechProbeActive)
                return;

            float duration = Time.time - _speechProbeStartedAt;
            if (duration < 0.25f)
            {
                // Too short to judge (a stray tick); wait for a real vocal.
                _speechProbeActive = false;
                return;
            }

            _speechProbeLogged = true;
            _speechProbeActive = false;
            LogFaceWarning(
                "[BundyFace] First speech envelope on '" + name + "': " +
                "duration=" + duration.ToString("F2") + "s, " +
                "clipDriven=" + _speechProbeClipDriven + ", " +
                "peakRms=" + _speechProbePeakRms.ToString("F4") + ", " +
                "peakJaw=" + _speechProbePeakJaw.ToString("F3") + " (maxJaw=" + maxJaw.ToString("F2") + ", exponent=" + envelopeExponent.ToString("F2") + "), " +
                "source='" + (voiceSource != null ? voiceSource.name : "<missing>") + "', " +
                "jawTargets=" + GetBoundTargetCount("Jaw_Open") + ", " +
                "jawBone=" + (_jawBone != null ? "resolved" : "MISSING") + ", " +
                "peakJawBoneDeg=" + (_speechProbePeakJaw * maxJawBoneDegrees).ToString("F2") + ".");
            // How far does Jaw_Open=100 actually move this head? Decides whether a subtle
            // mouth is a weight problem (fix mapping) or a weak blendshape (fix channels).
            LogDeformationProof("Jaw_Open");
        }

        private void UpdateBlink()
        {
            if (!autoBlink && !_blinkActive)
            {
                _blink = 0f;
                return;
            }

            float now = Time.time;
            if (!_blinkActive)
            {
                if (now < _nextBlinkAt)
                    return;
                TriggerBlink();
            }

            if (_blinkClosing)
            {
                _blink = Mathf.Clamp01(1f - (_blinkPhaseEnd - now) / Mathf.Max(0.01f, blinkCloseSeconds));
                if (now >= _blinkPhaseEnd)
                {
                    _blink = 1f;
                    _blinkClosing = false;
                    _blinkPhaseEnd = now + Mathf.Max(0.01f, blinkOpenSeconds);
                }
            }
            else
            {
                _blink = Mathf.Clamp01((_blinkPhaseEnd - now) / Mathf.Max(0.01f, blinkOpenSeconds));
                if (now >= _blinkPhaseEnd)
                {
                    _blink = 0f;
                    _blinkActive = false;
                    ScheduleNextBlink(now);
                }
            }
        }

        private void ApplyFace()
        {
            if (!_resolved)
                return;

            float speechActivity = maxJaw > 0.001f ? Mathf.Clamp01(_jaw / maxJaw) : 0f;
            float openNoise = Mathf.PerlinNoise(Time.time * 4.9f, 0.17f);
            float wideNoise = Mathf.PerlinNoise(Time.time * 5.7f, 0.53f);
            float tightNoise = Mathf.PerlinNoise(Time.time * 4.1f, 0.83f);
            float appliedJaw = 0f;

            for (int i = 0; i < DrivenChannels.Length; i++)
            {
                float value = 0f;
                string channel = DrivenChannels[i];

                switch (channel)
                {
                    case "Jaw_Open":
                    case "Jaw_Follow":
                        value = Mathf.Max(value, _jaw);
                        if (value > appliedJaw)
                            appliedJaw = value;
                        break;
                    case "V_Open":
                        if (animateVisemes)
                            value = Mathf.Max(value, speechActivity * (0.16f + 0.46f * openNoise));
                        break;
                    case "V_Wide":
                        if (animateVisemes)
                            value = Mathf.Max(value, speechActivity * 0.42f * wideNoise);
                        break;
                    case "V_Tight_O":
                        if (animateVisemes)
                            value = Mathf.Max(value, speechActivity * 0.50f * Mathf.Clamp01((tightNoise - 0.45f) * 1.8f));
                        break;
                    case "V_Dental_Lip":
                        if (animateVisemes)
                            value = Mathf.Max(value, speechActivity * 0.28f * Mathf.Clamp01((wideNoise - 0.58f) * 2.2f));
                        break;
                    case "V_Lip_Open":
                        if (animateVisemes)
                            value = Mathf.Max(value, speechActivity * 0.32f * Mathf.Clamp01((openNoise - 0.35f) * 1.55f));
                        break;
                    case "Eye_Blink_L":
                    case "Eye_Blink_R":
                    case "Lid_Close":
                        value = Mathf.Max(value, _blink);
                        break;
                }

                ApplyChannel(channel, Mathf.Clamp01(value));
            }

            ApplyJawBone(appliedJaw);

            if (logFirstBlinkDiagnostics && !_firstBlinkPeakLogged && _blink >= 0.999f)
            {
                _firstBlinkPeakLogged = true;
                LogFaceWarning(
                    "[BundyFace] First blink applied at peak on '" + name + "': " +
                    DescribeTargetWeights("Eye_Blink_L") + "; " +
                    DescribeTargetWeights("Eye_Blink_R") + "; " +
                    DescribeTargetWeights("Lid_Close") + ".");
                LogDeformationProof("Eye_Blink_L");
                StartCoroutine(LogEndOfFrameBlinkWeights());
            }
        }

        // The 2026-07-16 R28 in-game run proved that a 100.0 weight read-back is
        // not visual evidence: the weights were applied, read back, and no blink
        // was visible. Editor probes show the prefab AND built bundle meshes both
        // deform ~2cm when the weight is set, so the remaining fault is runtime
        // only. This one-shot probe bakes the live skinned head at the first
        // blink peak with the blink on and off, in the same frame with identical
        // bones, and reports actual vertex displacement plus renderer state.
        // A ~0.02 displacement here with no visible blink indicts the GPU
        // skinning/render path; a 0.0 displacement indicts the mesh/weight state.
        private void LogDeformationProof(string channel)
        {
            try
            {
                if (!_targets.TryGetValue(channel, out List<ShapeTarget> values) || values.Count == 0)
                {
                    LogFaceWarning("[BundyFace] Deformation proof skipped: no " + channel + " targets.");
                    return;
                }

                ShapeTarget head = null;
                foreach (ShapeTarget candidate in values)
                {
                    if (candidate.Renderer == null || candidate.Renderer.sharedMesh == null)
                        continue;
                    if (head == null ||
                        candidate.Renderer.sharedMesh.vertexCount > head.Renderer.sharedMesh.vertexCount)
                        head = candidate;
                }
                if (head == null)
                {
                    LogFaceWarning("[BundyFace] Deformation proof skipped: no live " + channel + " renderer.");
                    return;
                }

                SkinnedMeshRenderer renderer = head.Renderer;
                Mesh shared = renderer.sharedMesh;
                float savedWeight = renderer.GetBlendShapeWeight(head.Index);
                var driven = new Mesh();
                var neutral = new Mesh();
                float maxDelta = -1f;
                try
                {
                    renderer.SetBlendShapeWeight(head.Index, 100f);
                    renderer.BakeMesh(driven);
                    renderer.SetBlendShapeWeight(head.Index, 0f);
                    renderer.BakeMesh(neutral);

                    Vector3[] a = driven.vertices;
                    Vector3[] b = neutral.vertices;
                    int count = Mathf.Min(a.Length, b.Length);
                    maxDelta = 0f;
                    for (int i = 0; i < count; i++)
                    {
                        float magnitude = (a[i] - b[i]).magnitude;
                        if (magnitude > maxDelta)
                            maxDelta = magnitude;
                    }
                }
                finally
                {
                    renderer.SetBlendShapeWeight(head.Index, savedWeight);
                    Destroy(driven);
                    Destroy(neutral);
                }

                LogFaceWarning(
                    "[BundyFace] " + channel + " deformation proof on '" + renderer.name + "': " +
                    "bakedDeltaAt100=" + maxDelta.ToString("F5") + " (scale-baked units, blink baseline ~0.02), " +
                    "mesh='" + shared.name + "', verts=" + shared.vertexCount +
                    ", blendShapes=" + shared.blendShapeCount +
                    ", readable=" + shared.isReadable +
                    ", enabled=" + renderer.enabled +
                    ", activeInHierarchy=" + renderer.gameObject.activeInHierarchy +
                    ", isVisible=" + renderer.isVisible +
                    ", updateWhenOffscreen=" + renderer.updateWhenOffscreen +
                    ", forceMatrixRecalculation=" + renderer.forceMatrixRecalculationPerRender +
                    ", lossyScale=" + renderer.transform.lossyScale.ToString("F4") +
                    ", worldBounds=" + renderer.bounds.ToString("F2") + ".");
            }
            catch (Exception e)
            {
                // BakeMesh needs CPU-readable mesh data in a player build; a
                // failure here is itself diagnostic (bundle mesh not readable).
                LogFaceWarning("[BundyFace] " + channel + " deformation proof failed: " + e.GetType().Name + ": " + e.Message);
            }
        }

        // Read the blink weights again after every script's LateUpdate has run,
        // immediately before the frame renders. The in-LateUpdate read-back
        // above only proves this component's own write; if another component
        // zeroes the channels later in the same frame, only this log shows it.
        private IEnumerator LogEndOfFrameBlinkWeights()
        {
            yield return new WaitForEndOfFrame();
            LogFaceWarning(
                "[BundyFace] End-of-frame blink weights on '" + name + "' (as rendered): " +
                DescribeTargetWeights("Eye_Blink_L") + "; " +
                DescribeTargetWeights("Eye_Blink_R") + ".");
        }

        private string DescribeTargetWeights(string channel)
        {
            if (!_targets.TryGetValue(channel, out List<ShapeTarget> values) || values.Count == 0)
                return channel + "=<missing>";

            var parts = new string[values.Count];
            for (int i = 0; i < values.Count; i++)
            {
                ShapeTarget target = values[i];
                parts[i] = target.Renderer != null
                    ? target.Renderer.name + ":" + target.Renderer.GetBlendShapeWeight(target.Index).ToString("F1")
                    : "<destroyed>";
            }
            return channel + "=[" + string.Join(",", parts) + "]";
        }


        private bool HasTargets(string channel)
        {
            return _targets.TryGetValue(channel, out List<ShapeTarget> values) && values.Count > 0;
        }

        private void ApplyChannel(string channel, float normalizedValue)
        {
            if (!_targets.TryGetValue(channel, out List<ShapeTarget> values))
                return;

            float weight = normalizedValue * 100f;
            for (int i = 0; i < values.Count; i++)
            {
                ShapeTarget target = values[i];
                if (target.Renderer != null)
                    target.Renderer.SetBlendShapeWeight(target.Index, weight);
            }
        }

        private void ResetDrivenWeights()
        {
            foreach (KeyValuePair<string, List<ShapeTarget>> pair in _targets)
            {
                List<ShapeTarget> values = pair.Value;
                for (int i = 0; i < values.Count; i++)
                {
                    ShapeTarget target = values[i];
                    if (target.Renderer != null)
                        target.Renderer.SetBlendShapeWeight(target.Index, 0f);
                }
            }

            if (_jawBone != null)
                _jawBone.localRotation = _jawBoneBaseLocalRotation;
        }

        private void ScheduleNextBlink(float now, bool initial = false)
        {
            if (initial)
            {
                _nextBlinkAt = now + Mathf.Max(0.1f, firstBlinkDelaySeconds);
                return;
            }
            float min = Mathf.Max(0.1f, Mathf.Min(blinkIntervalMin, blinkIntervalMax));
            float max = Mathf.Max(min, Mathf.Max(blinkIntervalMin, blinkIntervalMax));
            _nextBlinkAt = now + UnityEngine.Random.Range(min, max);
        }

        // #716 F3: the face controller wrote straight to UnityEngine.Debug, so its lines landed
        // under Unity's source instead of Bundy's BepInEx logger. Severity is unchanged (these are
        // setup/proof failures, not per-frame chatter) and the "[BundyLipsync]"/"[BundyFace]"
        // prefixes inside the messages are left alone for the repo-wide prefix pass.
        private static void LogFaceWarning(string message)
        {
            if (BundyPlugin.Log != null)
                BundyPlugin.Log.LogWarning(message);
            else
                Debug.LogWarning(message);
        }
    }
